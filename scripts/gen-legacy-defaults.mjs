#!/usr/bin/env node
// Regenerates src/config/legacy-defaults.js from every revision of
// src/config/defaultConfig.toml in the git history plus the working-tree copy (#475).
//
//   node scripts/gen-legacy-defaults.mjs
//
// Run it (with full history, not a shallow clone) whenever a default [actions.*] field or
// [keymaps.*] binding changes, and commit the result. A test walks the same history and
// fails when the generated table is stale.

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { parse } from 'smol-toml'

const TOML_PATH = 'src/config/defaultConfig.toml'
const OUT_PATH = 'src/config/legacy-defaults.js'

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 1 << 28 })

/**
 * Every parsed revision of the bundled defaults, newest first, working tree included.
 * @returns {Object[]} parsed TOML objects
 */
export function readRevisions() {
  const revisions = [parse(readFileSync(TOML_PATH, 'utf8'))]
  for (const sha of git('log', '--full-history', '--format=%H', '--', TOML_PATH).trim().split('\n').filter(Boolean)) {
    revisions.push(parse(git('show', `${sha}:${TOML_PATH}`)))
  }
  return revisions
}

/**
 * Collect every shipped action field value and keymap binding.
 * @param {Object[]} revisions parsed defaults
 * @returns {{actions: Object, keymaps: Object}} value lists, exact and de-duplicated
 */
export function collect(revisions) {
  const actions = {}
  const keymaps = {}
  const add = (list, value) => {
    if (!list.some(v => JSON.stringify(v) === JSON.stringify(value))) list.push(value)
  }
  for (const rev of revisions) {
    for (const [id, action] of Object.entries(rev.actions || {})) {
      for (const [field, value] of Object.entries(action)) add(((actions[id] ||= {})[field] ||= []), value)
    }
    for (const [scope, bindings] of Object.entries(rev.keymaps || {})) {
      for (const [key, value] of Object.entries(bindings)) {
        if (typeof value === 'string') add(((keymaps[scope] ||= {})[key] ||= []), value)
      }
    }
  }
  return { actions, keymaps }
}

const lit = (v) => (Array.isArray(v) ? `[${v.map(lit).join(', ')}]` : JSON.stringify(v))

/**
 * Render the legacy-defaults.js module source.
 * @param {{actions: Object, keymaps: Object}} data collected values
 * @returns {string} file contents
 */
export function render({ actions, keymaps }) {
  let out = `/**
 * config/legacy-defaults.js - every value of [actions.*] and [keymaps.*] that a
 * release shipped in defaultConfig.toml, past or present (#475).
 *
 * GENERATED by scripts/gen-legacy-defaults.mjs from the revision history of
 * src/config/defaultConfig.toml. Do not edit by hand. When a default changes, run
 *   node scripts/gen-legacy-defaults.mjs
 * (needs full git history) and commit the result; migrate-frozen.test.js fails when
 * this table is stale. Entries are only ever added.
 *
 * Older releases copied the whole bundled defaults into the user file on first run, so
 * those copies cannot be told from intent unless we know what once was a default.
 * migrate-frozen.js ignores entries that match this table so current defaults apply.
 */

/** @type {Record<string, Record<string, unknown[]>>} action id -> field -> every value once shipped */
export const LEGACY_ACTION_VALUES = {
`
  for (const [id, fields] of Object.entries(actions)) {
    out += `  ${JSON.stringify(id)}: {\n`
    for (const [field, values] of Object.entries(fields)) out += `    ${field}: ${lit(values)},\n`
    out += '  },\n'
  }
  out += '}\n\n/** @type {Record<string, Record<string, string[]>>} keymap scope -> key -> every action id once shipped */\nexport const LEGACY_KEYMAP_BINDINGS = {\n'
  for (const [scope, bindings] of Object.entries(keymaps)) {
    out += `  ${JSON.stringify(scope)}: {\n`
    for (const [key, values] of Object.entries(bindings)) out += `    ${JSON.stringify(key)}: ${lit(values)},\n`
    out += '  },\n'
  }
  return `${out}}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUT_PATH, render(collect(readRevisions())))
  console.log(`wrote ${OUT_PATH}`)
}
